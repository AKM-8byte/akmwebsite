function detect() {
  const fromUrl = new URLSearchParams(location.search).get('lang');
  if (fromUrl === 'tr' || fromUrl === 'en') return fromUrl;
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === 'tr' || saved === 'en') return saved;
  } catch {
    /* depolama kapalı */
  }
  return (navigator.language || 'tr').toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

export const lang = detect();
export const locale = lang === 'tr' ? 'tr-TR' : 'en-GB';
document.documentElement.lang = lang;

export function t(key, vars = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.tr[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

// Verideki dile göre alan: L(film, 'title') → film.title_en ya da film.title_tr
export function L(obj, field) {
  if (!obj) return '';
  const other = lang === 'tr' ? 'en' : 'tr';
  const v = obj[`${field}_${lang}`];
  const empty = v == null || (Array.isArray(v) && !v.length) || v === '';
  return empty ? obj[`${field}_${other}`] ?? obj[field] ?? (Array.isArray(v) ? [] : '') : v;
}

export function setLang(next) {
  try {
    localStorage.setItem(KEY, next);
  } catch {
    /* depolama kapalı */
  }
  const url = new URL(location.href);
  url.searchParams.delete('lang');
  location.replace(url);
}

// HTML'deki data-i18n işaretli metinleri çevirir.
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-label]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nLabel)); });
  const title = document.querySelector('meta[name="i18n-title"]');
  if (title) document.title = t(title.content);
}
